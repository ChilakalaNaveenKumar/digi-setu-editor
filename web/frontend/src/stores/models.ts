/**
 * Model registry + active selection.
 *
 * The catalogue (`/api/models`) is plan-aware — the server filters the
 * list to what the user can pick AND tags entries with `available` so
 * locked models can be greyed-out with an Upgrade hint.
 *
 * `activeModelId` is the model the currently-open chat WS reports it
 * actually spawned with (via the `_session_info` event). It may differ
 * from `pinnedModelId` (the session's stored preference) if the user
 * downgraded their plan after pinning Opus, etc.
 */

import { defineStore } from "pinia";
import { computed, ref } from "vue";

import { listModels, setSessionModel as apiSetSessionModel } from "../api/models";
import type { ModelInfo } from "../api/types";

export const useModelsStore = defineStore("models", () => {
  const catalogue = ref<ModelInfo[]>([]);
  const defaultId = ref<string>("claude-sonnet-4-6");
  const planId = ref<string>("free");
  /**
   * Mirrors `byok_mode` from /api/models. Frontend uses this to
   * conditionally surface the BYOK/Cloud hint in the picker — when
   * the user has no keys configured every row is cloud and the
   * badge becomes visual noise.
   */
  const byokMode = ref(false);
  const loaded = ref(false);

  const pinnedModelId = ref<string | null>(null);
  const activeModelId = ref<string | null>(null);
  const activeModelName = ref<string | null>(null);

  async function refresh(): Promise<void> {
    try {
      const r = await listModels();
      catalogue.value = r.models;
      defaultId.value = r.default;
      planId.value = r.plan;
      byokMode.value = !!r.byok_mode;
      loaded.value = true;
    } catch (exc) {
      console.warn("[models] refresh failed", exc);
    }
  }

  function noteSessionInfo(model: string, modelName: string): void {
    activeModelId.value = model;
    activeModelName.value = modelName;
  }

  function setPinned(model: string | null): void {
    pinnedModelId.value = model;
  }

  /** PATCH the session's pinned model. UI calls this from the picker;
   * the change applies on the *next* prompt — the running pi keeps the
   * model it was spawned with.
   *
   * We also flip `activeModelId/Name` immediately so the header reflects
   * the user's choice right away. From the user's point of view, "active
   * model" means "the model my next message will use", not "the model
   * the still-streaming reply was generated by". The next `_session_info`
   * event after pi respawns will overwrite these with the same values.
   */
  async function pickForSession(sid: string, modelId: string): Promise<void> {
    await apiSetSessionModel(sid, modelId);
    pinnedModelId.value = modelId;
    const m = catalogue.value.find((x) => x.id === modelId);
    activeModelId.value = modelId;
    activeModelName.value = m?.name ?? modelId;
  }

  const byId = computed<Record<string, ModelInfo | undefined>>(() =>
    Object.fromEntries(catalogue.value.map((m) => [m.id, m])),
  );

  const grouped = computed<{ family: string; models: ModelInfo[] }[]>(() => {
    const groups = new Map<string, ModelInfo[]>();
    for (const m of catalogue.value) {
      if (!groups.has(m.family)) groups.set(m.family, []);
      groups.get(m.family)!.push(m);
    }
    return Array.from(groups.entries()).map(([family, models]) => ({ family, models }));
  });

  return {
    catalogue,
    defaultId,
    planId,
    byokMode,
    loaded,
    pinnedModelId,
    activeModelId,
    activeModelName,
    byId,
    grouped,
    refresh,
    noteSessionInfo,
    setPinned,
    pickForSession,
  };
});
