/** Same map but with `-open` suffix when expanded — Material Icon Theme
 *  ships open variants for every folder icon. */
function openVariant(closed: string): string {
  if (!closed.startsWith("material-icon-theme:folder")) return closed;
  return closed.replace("material-icon-theme:folder", "material-icon-theme:folder") + "-open";
}

const DEFAULT_FOLDER_CLOSED = "material-icon-theme:folder";
const DEFAULT_FOLDER_OPEN = "material-icon-theme:folder-open";
const DEFAULT_FILE = "material-icon-theme:file";

export function iconForPath(
  name: string,
  isDir: boolean,
  expanded = false,
): string {
  const lower = name.toLowerCase();

  if (isDir) {
    const closed = FOLDERNAME_ICONS_CLOSED[lower];
    if (closed) return expanded ? openVariant(closed) : closed;
    return expanded ? DEFAULT_FOLDER_OPEN : DEFAULT_FOLDER_CLOSED;
  }

  const filenameMatch = FILENAME_ICONS[lower];
  if (filenameMatch) return filenameMatch;

  const dot = name.lastIndexOf(".");
  const ext = dot > 0 && dot < name.length - 1 ? name.slice(dot + 1).toLowerCase() : "";
  if (ext && EXT_ICONS[ext]) return EXT_ICONS[ext];

  return DEFAULT_FILE;
}
